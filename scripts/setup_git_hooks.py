#!/usr/bin/env python
"""Setup Git Hooks for KnowledgeOS.

Creates a local pre-commit hook that runs schema validation.
Works with Git for Windows (sh hooks) and Unix.
"""
from __future__ import annotations

import os
import shlex
import subprocess
import sys
from pathlib import Path

VAULT_DIR = Path(__file__).resolve().parent.parent
HOOKS_DIR = VAULT_DIR / ".git" / "hooks"
sys.path.insert(0, str(VAULT_DIR))
from knowledgeos.data_ops import plain_vault_path
from knowledgeos.textio import atomic_create_bytes


def main() -> int:
    location = subprocess.run(["git", "-C", str(VAULT_DIR), "rev-parse", "--path-format=absolute", "--git-path", "hooks"], capture_output=True, text=True, timeout=30)
    if location.returncode:
        print("Error: Not a Git repository.", file=sys.stderr)
        return 1
    try:
        hooks_dir = plain_vault_path(VAULT_DIR, Path(location.stdout.strip()))
        hook_file = plain_vault_path(VAULT_DIR, hooks_dir / "pre-commit")
    except ValueError as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1

    # Use the current interpreter so Windows/venv python resolves correctly.
    python_exe = Path(sys.executable).as_posix()
    validate_script = (VAULT_DIR / "scripts" / "validate_schema.py").as_posix()
    vault_posix = VAULT_DIR.as_posix()

    hook_content = f"""#!/bin/sh
# KnowledgeOS pre-commit schema validation (generated by setup_git_hooks.py)
echo "Running KnowledgeOS pre-commit schema validation..."
cd {shlex.quote(vault_posix)} || exit 1
{shlex.quote(python_exe)} {shlex.quote(validate_script)}
EXIT_CODE=$?
if [ $EXIT_CODE -ne 0 ]; then
  echo "Git commit aborted: KnowledgeOS schema validation failed."
  exit $EXIT_CODE
fi
"""

    payload = hook_content.encode("utf-8")
    if hook_file.exists():
        if hook_file.read_bytes() == payload:
            if os.name == "posix" and not os.access(hook_file, os.X_OK):
                print(f"Error: Existing hook is not executable: {hook_file}", file=sys.stderr)
                return 1
            print(f"[OK] Hook already installed: {hook_file}")
            return 0
        print(f"Error: Preserving existing hook: {hook_file}", file=sys.stderr)
        return 1
    try:
        hooks_dir.mkdir(parents=True, exist_ok=True)
        plain_vault_path(VAULT_DIR, hook_file)
        atomic_create_bytes(hook_file, payload, mode=0o700 if os.name == "posix" else None)
    except (OSError, ValueError) as error:
        print(f"Error: Could not install pre-commit hook: {error}", file=sys.stderr)
        return 1

    print("[OK] Git pre-commit hook setup successfully!")
    return 0


if __name__ == "__main__":
    sys.exit(main())
